// License audit (NFR-8): every production dependency must carry an Apache-2.0-compatible license.
// `node scripts/check-licenses.mjs`          check; exit 1 on a disallowed or unknown license
// `node scripts/check-licenses.mjs --write`  also rewrite THIRD_PARTY_LICENSES.md
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ALLOWED = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'Apache-2.0',
  'MPL-2.0',
  'BlueOak-1.0.0',
  'CC0-1.0',
  'Unlicense',
  'Python-2.0',
  'CC-BY-4.0',
  'OFL-1.1'
])
// Packages whose package.json lacks a usable license field but whose license was checked by hand.
const MANUAL = {}

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'))
const rows = []
const problems = []
for (const [path, info] of Object.entries(lock.packages)) {
  if (!path || info.dev || info.devOptional || (info.optional && !existsSync(path))) continue
  if (!existsSync(path)) continue // platform-specific optional package not installed here
  const pkg = JSON.parse(readFileSync(join(path, 'package.json'), 'utf8'))
  const name = pkg.name ?? path.replace(/^.*node_modules\//, '')
  let license = MANUAL[name] ?? (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type)
  if (!license && Array.isArray(pkg.licenses))
    license = pkg.licenses.map((l) => l.type).join(' OR ')
  const ids = String(license ?? 'UNKNOWN')
    .replace(/[()]/g, '')
    .split(/\s+(?:OR|AND)\s+/)
  // For "A OR B" one allowed option is enough; for "A AND B" all must be allowed.
  const ok = /\sAND\s/.test(String(license))
    ? ids.every((i) => ALLOWED.has(i))
    : ids.some((i) => ALLOWED.has(i))
  rows.push({ name, version: pkg.version, license: license ?? 'UNKNOWN' })
  if (!ok) problems.push(`${name}@${pkg.version}: ${license ?? 'UNKNOWN'}`)
}
rows.sort((a, b) => a.name.localeCompare(b.name))

if (process.argv.includes('--write')) {
  const body = rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n')
  writeFileSync(
    'THIRD_PARTY_LICENSES.md',
    `# Third-party licenses\n\nProduction dependencies bundled with Tab King, generated by \`node scripts/check-licenses.mjs --write\`. Bundled assets (SoundFont, Bravura font) are listed in [NOTICE](NOTICE).\n\n| Package | Version | License |\n| --- | --- | --- |\n${body}\n`
  )
}
console.log(`${rows.length} production packages checked`)
if (problems.length) {
  console.error(`Disallowed or unknown licenses:\n  ${problems.join('\n  ')}`)
  process.exit(1)
}
